def write_numerical_diagnostics_csv(
    path: Path,
    convergence: Iterable[TalbotConvergenceDiagnostic],
    roots: Iterable[RootQualityDiagnostic],
    monte_carlo: Iterable[MonteCarloMonitoringDiagnostic] = (),
) -> None:
    """Write convergence and root-quality diagnostics to one compact CSV."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    records: list[dict[str, object]] = []
    for row in convergence:
        record = asdict(row)
        record["diagnostic"] = "talbot_convergence"
        records.append(record)
    for row in roots:
        record = asdict(row)
        record["diagnostic"] = "root_quality"
        records.append(record)
    for row in monte_carlo:
        record = asdict(row)
        record["diagnostic"] = "mc_monitoring_convergence"
        record["quantity"] = "p_surv_discretely_monitored"
        records.append(record)

    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=_CSV_FIELDS,
            extrasaction="ignore",
            lineterminator="\n",
        )
        writer.writeheader()
        for record in records:
            writer.writerow({field: record.get(field, "") for field in _CSV_FIELDS})
